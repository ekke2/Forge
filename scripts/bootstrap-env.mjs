// Writes .env.local for local development by reading the running Supabase stack.
//
//   npx supabase start          # if not already running
//   node scripts/bootstrap-env.mjs
//
// Safe to re-run; it overwrites .env.local with fresh local credentials.
import { execSync } from "node:child_process";
import { writeFileSync, existsSync } from "node:fs";

function fromStatus() {
  const raw = execSync("npx --yes supabase@latest status -o json", {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
  });
  const s = JSON.parse(raw);
  return {
    url: s.API_URL ?? "http://127.0.0.1:54321",
    publishable: s.PUBLISHABLE_KEY ?? s.ANON_KEY,
    secret: s.SECRET_KEY ?? s.SERVICE_ROLE_KEY,
  };
}

let cfg;
try {
  cfg = fromStatus();
} catch (err) {
  console.error(
    "Could not read `supabase status`. Is the stack running? (`npx supabase start`)",
  );
  console.error(String(err?.message ?? err));
  process.exit(1);
}

const body = `# Generated by scripts/bootstrap-env.mjs from the local Supabase stack.
NEXT_PUBLIC_SUPABASE_URL=${cfg.url}
NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${cfg.publishable}

# Server-only — the sync engine writes the *_cache tables with this (bypasses RLS).
SUPABASE_SERVICE_ROLE_KEY=${cfg.secret}

NEXT_PUBLIC_SITE_URL=http://localhost:3000

# "mock" = rich seeded GitHub dataset, no external calls. "live" = Octokit.
GITHUB_MODE=mock

# Protects /api/cron/sync.
CRON_SECRET=local-dev-cron-secret
`;

if (existsSync(".env.local") && !process.argv.includes("--force")) {
  console.log(".env.local already exists — pass --force to overwrite. Contents that would be written:\n");
  console.log(body);
  process.exit(0);
}

writeFileSync(".env.local", body, "utf8");
console.log("Wrote .env.local");
